// Offline, reproducible Node-only QuickJS bundle. Use preinstalled pinned packages.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const [toolchain, dependencies] = process.argv.slice(2);
if (!toolchain || !dependencies) throw new Error('Pass the existing esbuild toolchain and QuickJS package roots.');
const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.resolve(toolchain, 'package.json'));
const esbuild = require('esbuild');
if (esbuild.version !== '0.28.2') throw new Error('Expected esbuild 0.28.2.');
const modules = fs.realpathSync(path.resolve(dependencies, 'node_modules'));
const packages = ['quickjs-emscripten-core', '@jitl/quickjs-singlefile-cjs-release-sync', '@jitl/quickjs-ffi-types'];
for (const name of packages) {
  const packageFile = path.join(modules, name, 'package.json');
  const manifest = JSON.parse(fs.readFileSync(packageFile, 'utf8'));
  if (manifest.name !== name || manifest.version !== '0.32.0' || manifest.license !== 'MIT')
    throw new Error('Unexpected QuickJS package identity: ' + name);
}
const result = await esbuild.build({
  absWorkingDir: here,
  stdin: {
    sourcefile: 'quickjs-build-entry.cjs',
    resolveDir: modules,
    contents: `const { newQuickJSWASMModuleFromVariant } = require('quickjs-emscripten-core');
const variant = require('@jitl/quickjs-singlefile-cjs-release-sync').default;
module.exports = () => newQuickJSWASMModuleFromVariant(variant);`
  },
  platform: 'node',
  target: 'node24',
  format: 'cjs',
  bundle: true,
  write: false,
  minify: true,
  metafile: true,
  banner: { js: '// Generated by build-coding-runtime.mjs, QuickJS 0.32.0 (MIT). See licenses/QuickJS-LICENSE.txt.' },
});
for (const input of Object.keys(result.metafile.inputs)) {
  if (path.resolve(here, input) === path.join(modules, 'quickjs-build-entry.cjs')) continue;
  const relative = path.relative(modules, fs.realpathSync(path.resolve(here, input))).replaceAll(path.sep, '/');
  if (!packages.some(name => relative.startsWith(name + '/dist/')))
    throw new Error('Unexpected QuickJS build input: ' + relative);
}
const license = packages.map(name => name + ' 0.32.0\n\n' + fs.readFileSync(path.join(modules, name, 'LICENSE'), 'utf8').trimEnd()).join('\n\n');
const bytes = result.outputFiles[0].contents;
fs.writeFileSync(path.join(here, 'src/vendor/coding-runtime.cjs'), bytes);
fs.writeFileSync(path.join(here, 'licenses/QuickJS-LICENSE.txt'), license.replaceAll('\r\n','\n') + '\n');
console.log(JSON.stringify({bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), packages}));
